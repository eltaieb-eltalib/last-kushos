#!/usr/bin/env python3
"""Opt in selected static CPL artwork without changing dialog IDs or behavior.

Static ICON resources are loaded by the dialog manager and bypass LoadIcon macros.
Only anonymous, non-interactive System dialog artwork gets a dedicated control ID.
Existing interactive IDs, dialog IDs, resource IDs and layouts remain unchanged.
"""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parents[2]
SCOPES={'main':('keyboard.c','mouse.c'),'sysdm':('hardware.c','hardprof.c','userprofile.c')}
ICON=re.compile(r'(?m)^(\s*ICON\s+)(\w+)(\s*,\s*)(\w+|-1)(\s*,)')
report=[]
for mod,sources in SCOPES.items():
    folder=ROOT/'dll/cpl'/mod
    pairs={}
    if mod=='sysdm':
        names=['IDI_DEVMGR','IDI_ADDHW','IDI_HARDPROF','IDI_USERPROF']
        symbols={n:'IDC_KUSH_STATIC_'+n[4:] for n in names}
        header=folder/'resource.h';text=header.read_text()
        if 'KUSH_STATIC_CONTROL_IDS' not in text:
            text+='\n/* KUSH_STATIC_CONTROL_IDS: non-interactive artwork only. */\n'
            text+=''.join(f'#define {symbols[n]} {62001+i}\n' for i,n in enumerate(names))
            header.write_text(text)
        for rc in sorted((folder/'lang').glob('*.rc')):
            raw=rc.read_bytes();bom=raw.startswith(b'\xef\xbb\xbf');text=raw.decode('utf-8-sig')
            def replace(m):
                if m[2] in symbols and m[4] in ('IDC_STATIC','-1'):
                    return m[1]+m[2]+m[3]+symbols[m[2]]+m[5]
                return m[0]
            new=ICON.sub(replace,text)
            if new!=text:rc.write_bytes((b'\xef\xbb\xbf' if bom else b'')+new.encode())
    text=(folder/'lang/en-US.rc').read_text(encoding='utf-8-sig')
    for m in ICON.finditer(text):
        icon,control=m[2],m[4]
        if control in ('IDC_STATIC','-1'):continue
        if control in pairs and pairs[control]!=icon:raise RuntimeError('Ambiguous control ID '+control)
        pairs[control]=icon
    function='KushRefresh'+mod.title()+'StaticIcons'
    text='/* Generated by tools/icons/refresh_static_fluent.py. */\n#pragma once\n#include <kushicons.h>\n'
    text+=f'static __inline void {function}(HWND dialog)\n{{\n'
    text+=''.join(f'    KushSetDialogIcon(dialog, {control}, hApplet, {icon});\n' for control,icon in pairs.items())
    text+='}\n';(folder/'kush_static_icons.h').write_text(text)
    for filename in sources:
        p=folder/filename;text=p.read_text(encoding='utf-8')
        include='#include "kush_static_icons.h"'
        if include not in text:
            inc=list(re.finditer(r'(?m)^#include[^\n]*',text));assert inc
            pos=inc[-1].end();text=text[:pos]+'\n'+include+text[pos:]
        call=f'            {function}(hwndDlg);'
        text=re.sub(r'(case WM_INITDIALOG:\n)(?!'+re.escape(call)+r')',r'\1'+call+'\n',text)
        p.write_text(text,encoding='utf-8')
    report.append({'module':mod,'mapped_controls':len(pairs),'routes':list(sources)})
print(json.dumps(report,indent=2))
